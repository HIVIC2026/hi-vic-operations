// Regenerates src/lib/statement-of-rights.data.ts from docs/esc-forms/veu-statement-of-rights.pdf.
// Usage: bun scripts/embed-statement-of-rights.ts [pdfPath] [outPath]   (both optional; defaults below)
// The file must be the real ESC "Consumer Statement of Rights – VEU program" PDF, embedded byte for byte.
// A missing file, or anything that is not a PDF (%PDF- header), embeds null — never a fabricated document.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { looksLikePdf } from "../src/lib/product-warranty.core";

const ROOT = new URL("..", import.meta.url).pathname;
const REL = "docs/esc-forms/veu-statement-of-rights.pdf";
const abs = process.argv[2] ?? join(ROOT, REL);
const outPath = process.argv[3] ?? join(ROOT, "src/lib/statement-of-rights.data.ts");
const day = new Date().toISOString().slice(0, 10);
let value = "null";
let note = `file not found (${REL})`;
if (existsSync(abs)) {
  const bytes = new Uint8Array(readFileSync(abs));
  if (!looksLikePdf(bytes)) note = `REJECTED — not a PDF (header ${JSON.stringify(Buffer.from(bytes.slice(0, 8)).toString("latin1"))})`;
  else {
    const sha = createHash("sha256").update(bytes).digest("hex");
    value = JSON.stringify(`data:application/pdf;base64,${Buffer.from(bytes).toString("base64")}`);
    note = `embedded ${bytes.length} bytes, sha256 ${sha}`;
  }
}
const out = `// GENERATED by \`bun scripts/embed-statement-of-rights.ts\` from ${REL} — do not edit by hand.
// The ESC's own "Consumer Statement of Rights – VEU program" v1.2 (1 May 2024), unmodified. null = not on file.
// Generated ${day}: ${note}.
export const STATEMENT_OF_RIGHTS_PDF: string | null = ${value};
`;
writeFileSync(outPath, out);
console.log(`${REL}: ${note}`);
