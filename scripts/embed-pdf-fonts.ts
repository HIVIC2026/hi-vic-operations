// Regenerates src/lib/pdf-fonts.data.ts (Open Sans 400/700/700-italic/800, latin subset, base64) for the shared PDF kit.
// Usage: bun scripts/embed-pdf-fonts.ts   (reads node_modules/@fontsource/open-sans, a devDependency)
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const lines: string[] = [];
for (const [w, style] of [[400, "normal"], [700, "normal"], [700, "italic"], [800, "normal"]] as const) {
  const name = style === "italic" ? `${w}_ITALIC` : `${w}`;
  const bytes = readFileSync(join(ROOT, `node_modules/@fontsource/open-sans/files/open-sans-latin-${w}-${style}.woff`));
  const sha = createHash("sha256").update(bytes).digest("hex");
  lines.push(`/** Open Sans ${w} ${style}, latin subset (WOFF), sha256 ${sha.slice(0, 16)}... */\nexport const OPEN_SANS_${name} = ${JSON.stringify(bytes.toString("base64"))};`);
}
writeFileSync(join(ROOT, "src/lib/pdf-fonts.data.ts"), `// GENERATED by \`bun scripts/embed-pdf-fonts.ts\` from @fontsource/open-sans - do not edit by hand.\n${lines.join("\n")}\n`);
console.log("wrote src/lib/pdf-fonts.data.ts");
