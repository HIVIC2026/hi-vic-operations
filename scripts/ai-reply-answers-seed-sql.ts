// Writes the seed block of docs/pending-migrations/ai-reply-answers.sql from AI_SEED_ANSWERS (final review C1).
// The block inserts Jo's starting answers (sort 1..n) only when the table is empty, so applying twice never duplicates.
// tests/ai-reply-answers-db.test.ts fails if the SQL and AI_SEED_ANSWERS ever differ.
// Usage: bun scripts/ai-reply-answers-seed-sql.ts --write
import { readFileSync, writeFileSync } from "node:fs";
import { AI_SEED_ANSWERS, type AiAnswer } from "../src/lib/ai-answers.core";

export const SEED_START = "-- BEGIN seed (generated by scripts/ai-reply-answers-seed-sql.ts from AI_SEED_ANSWERS — do not edit by hand)";
export const SEED_END = "-- END seed";
const SQL_PATH = "docs/pending-migrations/ai-reply-answers.sql";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function seedBlock(answers: AiAnswer[]): string {
  const values = answers.map((a, i) => `  (${lit(a.topic)}, ${lit(a.answer)}, ${i + 1})`).join(",\n");
  return [
    SEED_START,
    "-- Jo's starting answers, only into an empty table.",
    "INSERT INTO public.ai_reply_answers (topic, answer, active, sort)",
    "SELECT v.topic, v.answer, true, v.sort FROM (VALUES",
    values,
    ") AS v(topic, answer, sort)",
    "WHERE NOT EXISTS (SELECT 1 FROM public.ai_reply_answers);",
    SEED_END,
  ].join("\n");
}

if (import.meta.main && process.argv.includes("--write")) {
  const sql = readFileSync(SQL_PATH, "utf8");
  const a = sql.indexOf(SEED_START);
  const b = sql.indexOf(SEED_END);
  const block = seedBlock(AI_SEED_ANSWERS);
  const next = a >= 0 && b > a ? sql.slice(0, a) + block + sql.slice(b + SEED_END.length) : `${sql.trimEnd()}\n${block}\n`;
  writeFileSync(SQL_PATH, next);
  console.log(`Wrote ${AI_SEED_ANSWERS.length} seed rows to ${SQL_PATH}`);
}
