// Regenerates src/lib/veu-factsheet.data.ts from docs/esc-forms/veu-consumer-factsheet.pdf (decision 320).
// Usage: bun scripts/embed-veu-factsheet.ts
// The file must be the real ESC "Victorian Energy Upgrades consumer factsheet" PDF downloaded from the ESC website.
// A missing file, or anything that is not a PDF (%PDF- header), embeds null — never a fabricated document.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { VEU_FACTSHEET_PATH } from "../src/lib/veu-factsheet.core";
import { looksLikePdf } from "../src/lib/product-warranty.core";

const ROOT = new URL("..", import.meta.url).pathname;
const abs = join(ROOT, VEU_FACTSHEET_PATH);
const day = new Date().toISOString().slice(0, 10);
let value = "null";
let note = `file not found (Jo to download the current ESC VEU consumer factsheet into that path)`;
if (existsSync(abs)) {
  const bytes = new Uint8Array(readFileSync(abs));
  if (!looksLikePdf(bytes)) note = `REJECTED — not a PDF (header ${JSON.stringify(Buffer.from(bytes.slice(0, 8)).toString("latin1"))})`;
  else {
    const sha = createHash("sha256").update(bytes).digest("hex");
    value = JSON.stringify(`data:application/pdf;base64,${Buffer.from(bytes).toString("base64")}`);
    note = `embedded ${bytes.length} bytes, sha256 ${sha}`;
  }
}
const out = `// GENERATED by \`bun scripts/embed-veu-factsheet.ts\` from ${VEU_FACTSHEET_PATH} — do not edit by hand.
// null = the factsheet is not on file: the "You're in" email (O22) sends without it and nothing is recorded.
// Generated ${day}: ${note}.
export const VEU_FACTSHEET_PDF: string | null = ${value};
`;
writeFileSync(join(ROOT, "src/lib/veu-factsheet.data.ts"), out);
console.log(`${VEU_FACTSHEET_PATH}: ${note}`);
