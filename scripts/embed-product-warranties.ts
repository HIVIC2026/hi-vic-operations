// Regenerates src/lib/product-warranty.data.ts from the PDFs in docs/product-warranties/.
// Usage: bun scripts/embed-product-warranties.ts
// Only files named in product-warranty.core PRODUCT_WARRANTIES are embedded; each must be a real PDF (%PDF- header) whose
// text mentions a warranty term (so a saved HTML error page or the wrong file can never reach an owner). A missing file is
// reported and left out — never fabricated.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { PRODUCT_WARRANTIES, looksLikePdf } from "../src/lib/product-warranty.core";

const ROOT = new URL("..", import.meta.url).pathname;
const entries: string[] = [];
const report: string[] = [];
for (const w of PRODUCT_WARRANTIES) {
  const abs = join(ROOT, w.pdfPath);
  if (!existsSync(abs)) { report.push(`MISSING  ${w.pdfPath} — ${w.requestFrom ?? `download from ${w.sourceUrls.join(" or ")}`}`); continue; }
  const bytes = new Uint8Array(readFileSync(abs));
  if (!looksLikePdf(bytes)) { report.push(`REJECTED ${w.pdfPath} — not a PDF (header ${JSON.stringify(Buffer.from(bytes.slice(0, 8)).toString("latin1"))})`); continue; }
  const text = Buffer.from(bytes).toString("latin1");
  if (!/warrant/i.test(text)) report.push(`WARNING  ${w.pdfPath} — no plain-text "warranty" found (scanned/compressed PDF?). Check the file by eye before relying on it.`);
  const sha = createHash("sha256").update(bytes).digest("hex");
  entries.push(`  ${JSON.stringify(w.pdfPath)}: ${JSON.stringify(`data:application/pdf;base64,${Buffer.from(bytes).toString("base64")}`)}, // sha256 ${sha} (${bytes.length} bytes)`);
  report.push(`OK       ${w.pdfPath} — ${bytes.length} bytes, sha256 ${sha.slice(0, 16)}…`);
}
const out = `// GENERATED by \`bun scripts/embed-product-warranties.ts\` from the PDFs in docs/product-warranties/ — do not edit by hand.
// Key = repo path (product-warranty.core \`pdfPath\`), value = the PDF as a base64 data URI. A product with no entry here
// has no warranty copy on file: the completion pack sends without it and the AP signature holds on that product.
// Generated ${new Date().toISOString().slice(0, 10)}. See docs/product-warranties/README.md for each document's source.
export const PRODUCT_WARRANTY_PDFS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`;
writeFileSync(join(ROOT, "src/lib/product-warranty.data.ts"), out);
console.log(report.join("\n"));
console.log(`\nEmbedded ${entries.length} of ${PRODUCT_WARRANTIES.length} warranty documents → src/lib/product-warranty.data.ts`);
