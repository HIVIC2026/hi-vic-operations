// Regenerates src/lib/product-instructions.data.ts from the PDFs in docs/product-instructions/.
// Usage: bun scripts/embed-product-instructions.ts
// Speed (Jo 7 Nov 2026): the PDFs are no longer embedded. Upload each new/changed PDF first with
//   lovable-assets create --file docs/product-instructions/<name>.pdf --filename <name>.pdf > src/lib/product-instructions-files/<name>.pdf.asset.json
// and this script records each pointer with the PDF's SHA-256 and size (a missing or wrong-size pointer is rejected).
// Only files named in product-instructions.core PRODUCT_INSTRUCTIONS are embedded; each must be a real PDF (%PDF- header),
// and its sourceUrl must not be a reseller host. A missing file is reported and left out — never fabricated.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { looksLikePdf } from "../src/lib/product-warranty.core";
import { PRODUCT_INSTRUCTIONS } from "../src/lib/product-instructions.list";

const entries0 = PRODUCT_INSTRUCTIONS;
if (entries0.length === 0) { console.error("No instruction documents listed in product-instructions.list.ts"); process.exit(1); }
const RESELLER = /(bunnings|bunnings\.com|amazon|ebay|bigw|mitre10|reece|totaltools)/i;

// INSTRUCTIONS_ROOT is for tests only (a temp dir holding docs/product-instructions and src/lib).
const ROOT = process.env.INSTRUCTIONS_ROOT ?? new URL("..", import.meta.url).pathname;
const entries: string[] = [];
const imports: string[] = [];
const report: string[] = [];
let rejected = 0;
for (const e of entries0) {
  const abs = join(ROOT, e.pdfPath);
  if (RESELLER.test(e.sourceUrl)) { rejected++; report.push(`REJECTED ${e.pdfPath} — reseller host in sourceUrl ${e.sourceUrl}`); continue; }
  if (!existsSync(abs)) { report.push(`MISSING  ${e.pdfPath} — download from ${e.sourceUrl}`); continue; }
  const bytes = new Uint8Array(readFileSync(abs));
  if (!looksLikePdf(bytes)) { rejected++; report.push(`REJECTED ${e.pdfPath} — not a PDF (header ${JSON.stringify(Buffer.from(bytes.slice(0, 8)).toString("latin1"))})`); continue; }
  const sha = createHash("sha256").update(bytes).digest("hex");
  const name = e.pdfPath.split("/").pop()!;
  const pointerRel = `src/lib/product-instructions-files/${name}.asset.json`;
  const pointerAbs = join(ROOT, pointerRel);
  if (!existsSync(pointerAbs)) { rejected++; report.push(`REJECTED ${e.pdfPath} — no stored copy; run: lovable-assets create --file ${e.pdfPath} --filename ${name} > ${pointerRel}`); continue; }
  const pointer = JSON.parse(readFileSync(pointerAbs, "utf8")) as { url?: string; size?: number };
  if (typeof pointer.url !== "string" || pointer.size !== bytes.length) { rejected++; report.push(`REJECTED ${e.pdfPath} — stored copy ${pointerRel} does not match this PDF (size ${pointer.size} vs ${bytes.length}); upload it again`); continue; }
  const ident = name.replace(/\.pdf$/, "").replace(/[^A-Za-z0-9]+(.)?/g, (_m, c: string | undefined) => (c ? c.toUpperCase() : "")).replace(/^./, (c) => c.toLowerCase());
  imports.push(`import ${ident} from "./product-instructions-files/${name}.asset.json";`);
  entries.push(`  ${JSON.stringify(e.pdfPath)}: { url: ${ident}.url, sha256: ${JSON.stringify(sha)}, size: ${bytes.length} },`);
  report.push(`OK       ${e.pdfPath} — ${bytes.length} bytes, sha256 ${sha.slice(0, 16)}…`);
}
const out = `// GENERATED by \`bun scripts/embed-product-instructions.ts\` from the PDFs in docs/product-instructions/ — do not edit by hand.
// Key = repo path (product-instructions.core \`pdfPath\`), value = where the identical copy is stored (Lovable file store,
// pointer in src/lib/product-instructions-files/) plus its SHA-256 and size. A family with no entry here has no
// instructions on file: instructionsForOption returns null and Part 4 holds with instructionsHoldReason.
// Speed (Jo 7 Nov 2026): the PDFs are no longer built into the server program; product-instructions.server fetches the
// copy and refuses it unless its SHA-256 matches. See docs/product-instructions/README.md for each document's source.
${imports.join("\n")}

export type InstructionFile = { url: string; sha256: string; size: number };

export const PRODUCT_INSTRUCTION_FILES: Readonly<Record<string, InstructionFile>> = {
${entries.join("\n")}
};
`;
console.log(report.join("\n"));
// Validate everything first: on any rejection exit 1 and leave the data file untouched.
if (rejected) { console.error(`\n${rejected} file(s) rejected — data file NOT written. Fix before committing.`); process.exit(1); }
writeFileSync(join(ROOT, "src/lib/product-instructions.data.ts"), out);
console.log(`\nRecorded ${entries.length} of ${entries0.length} instruction documents → src/lib/product-instructions.data.ts`);
